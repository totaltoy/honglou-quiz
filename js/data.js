/* ============================================================
 * 计分：用户答案 → 六维向量（归一化到 0~5）→ 与角色原型匹配
 * ============================================================ */
function dimMaxPossible() {
  return DIMS.map((d) =>
    QUESTIONS.reduce((sum, q) => {
      const best = Math.max(0, ...q.options.map((o) => o.score[d] || 0));
      return sum + best;
    }, 0)
  );
}

function scoreAnswers(answers) {
  const raw = {};
  DIMS.forEach((d) => (raw[d] = 0));
  QUESTIONS.forEach((q, i) => {
    const opt = q.options[answers[i]];
    if (!opt) return;
    for (const [d, v] of Object.entries(opt.score)) raw[d] += v;
  });

  const max = dimMaxPossible();
  const u = DIMS.map((d, i) => (max[i] > 0 ? (raw[d] / max[i]) * 5 : 0));

  const ranked = CHARACTERS.map((c) => {
    const v = DIMS.map((d) => c.vector[d]);
    const dist = Math.sqrt(u.reduce((s, x, i) => s + (x - v[i]) ** 2, 0));
    return { c, dist };
  }).sort((a, b) => a.dist - b.dist);

  const MAX_DIST = Math.sqrt(DIMS.length) * 5;
  const pct = (entry) => Math.round(55 + (1 - entry.dist / MAX_DIST) * 43);

  return {
    u, // 归一化六维（0~5）
    raw, // 原始累加分
    ranked,
    top: ranked[0],
    shadow: ranked[1],
    topPct: pct(ranked[0]),
    shadowPct: pct(ranked[1]),
  };
}

